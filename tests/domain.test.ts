import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdirSync, mkdtempSync } from 'node:fs';
import { join } from 'node:path';
import { Store } from '../electron/store.js';
import { Scheduler } from '../electron/scheduler.js';
import { conflictingKeys, expand, isActive, reminderCandidates, validateInput } from '../src/shared/domain.js';
import { parseClock } from '../src/shared/time.js';
import type { ItemInput } from '../src/shared/types.js';
const ms = (stamp: string) => +new Date(stamp);
const created = ms('2026-09-20T08:00');
const input = (patch: Partial<ItemInput> = {}): ItemInput => ({ title: '冥想', notes: '', date: '2026-09-20', startAt: '2026-09-20T15:00', endAt: '2026-09-20T16:00', repeat: { kind: 'none', weekdays: [], until: null }, reminders: [{ anchor: 'start', minutes: 10 }, { anchor: 'start', minutes: 0 }, { anchor: 'end', minutes: 0 }], ...patch });

test('manual minute precision, 24:00 month rollover, and invalid inputs', () => {
  assert.equal(parseClock('2026-09-20', '9', '7'), '2026-09-20T09:07');
  assert.equal(parseClock('2026-12-31', '24', '00'), '2027-01-01T00:00');
  assert.throws(() => parseClock('2026-09-20', '24', '05'));
  assert.throws(() => parseClock('2026-09-20', '12', '60'));
  assert.throws(() => parseClock('2026-02-30', '12', '00'));
  assert.throws(() => validateInput(input({ endAt: '2026-09-20T14:00' })));
  assert.throws(() => validateInput(input({ title: '   ' })));
});
test('recurring expansion honors weekdays, end date, and overnight overlap', () => {
  const s = new Store(':memory:');
  s.save({ value: input({ startAt: '2026-09-20T23:30', endAt: '2026-09-21T00:30', repeat: { kind: 'weekly', weekdays: [0, 2], until: '2026-09-27' } }) }, created);
  assert.equal(expand(s.snapshot(), '2026-09-21', '2026-09-22').length, 1);
  assert.equal(expand(s.snapshot(), '2026-09-20', '2026-10-01').length, 3);
  s.close();
});
test('early completion cancels all future reminders for only that occurrence; undo does not replay old reminders', () => {
  const s = new Store(':memory:');
  const id = s.save({ value: input({ repeat: { kind: 'daily', weekdays: [], until: null } }) }, created);
  const target = { itemId: id, occurrenceDate: '2026-09-20' };
  s.complete({ ...target, completed: true }, ms('2026-09-20T14:30'));
  assert.equal(reminderCandidates(s.snapshot(), ms('2026-09-20T14:00'), ms('2026-09-20T17:00')).length, 0);
  assert.equal(expand(s.snapshot(), '2026-09-21', '2026-09-22')[0].completedAt, null);
  s.complete({ ...target, completed: false }, ms('2026-09-20T15:30'));
  const reminders = reminderCandidates(s.snapshot(), ms('2026-09-20T14:00'), ms('2026-09-20T17:00'));
  assert.deepEqual(reminders.map(r => r.rule.anchor), ['end']);
  const o = expand(s.snapshot(), '2026-09-20', '2026-09-21')[0];
  assert.equal(isActive(o, ms('2026-09-20T15:40')), true);
  assert.equal(isActive(o, ms('2026-09-20T16:00')), false);
  s.close();
});
test('single occurrence can move outside original date range without duplication', () => {
  const s = new Store(':memory:');
  const id = s.save({ value: input({ repeat: { kind: 'daily', weekdays: [], until: '2026-09-22' } }) }, created);
  s.save({ target: { itemId: id, occurrenceDate: '2026-09-21', scope: 'single' }, value: input({ title: '改期', date: '2026-10-01', startAt: '2026-10-01T10:00', endAt: '2026-10-01T11:00' }) }, created);
  assert.equal(expand(s.snapshot(), '2026-09-21', '2026-09-22').length, 0);
  assert.equal(expand(s.snapshot(), '2026-10-01', '2026-10-02')[0].title, '改期');
  assert.equal(expand(s.snapshot(), '2026-09-20', '2026-10-02').length, 3);
  s.close();
});
test('future series edit preserves earlier days and future completion', () => {
  const s = new Store(':memory:');
  const id = s.save({ value: input({ repeat: { kind: 'daily', weekdays: [], until: null } }) }, created);
  s.complete({ itemId: id, occurrenceDate: '2026-09-23', completed: true }, created + 1);
  s.save({ target: { itemId: id, occurrenceDate: '2026-09-22', scope: 'future' }, value: input({ title: '健身', date: '2026-09-22', startAt: '2026-09-22T17:00', endAt: '2026-09-22T18:00', repeat: { kind: 'daily', weekdays: [], until: null } }) }, created + 2);
  const occurrences = expand(s.snapshot(), '2026-09-20', '2026-09-25');
  assert.deepEqual(occurrences.map(o => o.title), ['冥想', '冥想', '健身', '健身', '健身']);
  assert.ok(occurrences[3].completedAt);
  s.close();
});
test('delete single and future recurrence; untimed task can become a timed event', () => {
  const s = new Store(':memory:');
  const id = s.save({ value: input({ repeat: { kind: 'daily', weekdays: [], until: null } }) }, created);
  s.remove({ itemId: id, occurrenceDate: '2026-09-21', scope: 'single' });
  s.remove({ itemId: id, occurrenceDate: '2026-09-23', scope: 'future' });
  assert.deepEqual(expand(s.snapshot(), '2026-09-20', '2026-09-28').map(o => o.date), ['2026-09-20', '2026-09-22']);
  const task = s.save({ value: input({ title: '待辦', startAt: null, endAt: null }) }, created);
  assert.equal(reminderCandidates(s.snapshot(), created, ms('2026-09-20T18:00')).filter(r => r.occurrence.itemId === task).length, 0);
  s.save({ target: { itemId: task, occurrenceDate: '2026-09-20', scope: 'single' }, value: input({ title: '待辦' }) }, created);
  assert.equal(s.getOccurrence({ itemId: task, occurrenceDate: '2026-09-20' }).startAt, '2026-09-20T15:00');
  s.close();
});
test('conflicts allow touching boundaries and exclude completed items', () => {
  const s = new Store(':memory:');
  s.save({ value: input() }, created);
  s.save({ value: input({ startAt: '2026-09-20T16:00', endAt: '2026-09-20T17:00' }) }, created);
  assert.equal(conflictingKeys(expand(s.snapshot(), '2026-09-20', '2026-09-21')).size, 0);
  const id = s.save({ value: input({ startAt: '2026-09-20T15:30', endAt: '2026-09-20T16:30' }) }, created);
  assert.equal(conflictingKeys(expand(s.snapshot(), '2026-09-20', '2026-09-21')).size, 3);
  s.complete({ itemId: id, occurrenceDate: '2026-09-20', completed: true }, created);
  assert.equal(conflictingKeys(expand(s.snapshot(), '2026-09-20', '2026-09-21')).size, 0);
  s.close();
});
test('scheduler sends every rule once, survives restart and backward clock changes', async () => {
  const s = new Store(':memory:');
  s.save({ value: input() }, created);
  const calls: { count: number; missed: boolean }[] = [];
  const notify = async (due: unknown[], missed: boolean) => { calls.push({ count: due.length, missed }); return { display: 'shown', audio: 'played' } as const; };
  const scheduler = new Scheduler(s, notify);
  await scheduler.tick(ms('2026-09-20T14:49:59'));
  await scheduler.tick(ms('2026-09-20T14:50:00'));
  await scheduler.tick(ms('2026-09-20T14:50:01'));
  await scheduler.tick(ms('2026-09-20T14:49:59'));
  await scheduler.tick(ms('2026-09-20T14:50:00'));
  assert.deepEqual(calls, [{ count: 1, missed: false }]);
  await new Scheduler(s, notify).tick(ms('2026-09-20T16:30'));
  assert.deepEqual(calls.at(-1), { count: 2, missed: true });
  const count = calls.length;
  await new Scheduler(s, notify).tick(ms('2026-09-21T09:00'));
  assert.equal(calls.length, count);
  s.close();
});
test('editing after earlier reminders skips past times; deleted events never notify', () => {
  const s = new Store(':memory:');
  const id = s.save({ value: input() }, created);
  s.save({ target: { itemId: id, occurrenceDate: '2026-09-20', scope: 'single' }, value: input() }, ms('2026-09-20T15:30'));
  assert.equal(reminderCandidates(s.snapshot(), created, ms('2026-09-20T17:00')).length, 1);
  s.remove({ itemId: id, occurrenceDate: '2026-09-20', scope: 'single' });
  assert.equal(reminderCandidates(s.snapshot(), created, ms('2026-09-20T17:00')).length, 0);
  s.close();
});
test('database persists data and preset changes do not rename existing events', () => {
  mkdirSync('test-results', { recursive: true });
  const dir = mkdtempSync(join(process.cwd(), 'test-results', 'store-'));
  const path = join(dir, 'daybook.sqlite');
  let s = new Store(path);
  const id = s.save({ value: input() }, created);
  s.complete({ itemId: id, occurrenceDate: '2026-09-20', completed: true }, created);
  const presets = s.snapshot().presets;
  s.savePresets([{ ...presets[0], title: '靜心' }, ...presets.slice(1)].reverse());
  s.close(); s = new Store(path);
  assert.equal(s.snapshot().presets.at(-1)!.title, '靜心');
  assert.equal(s.snapshot().items[0].title, '冥想');
  assert.equal(s.snapshot().states[0].completedAt, created);
  s.close();
});
